#include <stdio.h>
int main(void){
    int a=0,b=1;
    char c='a';
    int *pa,*pb;
    char *pc;
    printf("a is %d,&a is %p,pa is %p\n",a,&a,pa);
    printf("b is %d,&b is %p,pa is %p\n",b,&b,pb);
    printf("c is %c,&c is %p,pa is %p\n",c,&c,pc);
    return 0;
}
