#include <stdio.h>
int main() {
    int a=0,b=1;
    char  c='a';
    printf("a is %d,&a is %p\n",a,&a);
    printf("b is %d,&b is %p\n",b,&b);
    printf("c is %c,&c is %p\n",c,&c);
    return 0;
}
//输出结果：
//a is 0,&a is 00000000005FFE6C
//b is 1,&b is 00000000005FFE68
//c is a,&c is 00000000005FFE67
//从输出结果可以看出，变量a、b、c在内存中的地址是连续的，且地址是从大到小排列的。
//这是因为在大多数系统中，栈是向下增长的，即高地址向低地址增长。
//另外，int类型占用4个字节，char类型占用1个字节，因此变量b的地址比变量a的地址小4个字节，变量c的地址比变量b的地址小1个字节。
//需要注意的是，变量的地址分配是由编译器和操作系统决定的，不同的编译器和操作系统可能会有不同的地址分配方式。
//另外，编译器可能会对变量进行对齐处理，以提高访问效率，因此在某些情况下，变量的地址可能不是完全连续的。
//此外，局部变量通常存储在栈区，而全局变量和静态变量则存储在数据区或BSS区，它们的地址分配方式也有所不同。
//总结：通过打印变量的地址，可以观察到变量在内存中的分配情况和栈的增长方向，但具体的地址分配方式可能因编译器和操作系统而异，需要根据具体情况进行分析。本例仅供参考。