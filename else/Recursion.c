#include <stdio.h>
long Fact(int n);
int main(void){
    int n;
    long m;
    printf("请输入一个正整数：\n");
    scanf("%d",&n);
    m=Fact(n);
    printf("%d的阶乘是%ld\n",n,m);
    return 0;

}
long Fact(int n){
    if(n<0){
        return -1;
    }
    else if(n==0||n==1){
        return 1;
    }
    else{
        return n*Fact(n-1);
    }
}
//递归的优点：符合人的思维方式，更加简洁，易于理解
//递归的缺点：占用内存多，效率低，容易引起栈溢出
//递归函数的三个要素：1.递归终止条件 2.递归体 3.递归方向
//递归函数的执行过程：递归函数每调用一次，系统就为该函数分配一块独立的内存空间，用于存放该函数的局部变量和参数，当函数执行完毕后，系统会释放该内存空间
//递归函数的应用场景：适用于解决那些可以分解为相似子问题的问题，如阶乘、斐波那契数列、汉诺塔问题等
//注意事项：1.递归函数必须有终止条件，否则会导致无限递归 2.递归函数的参数和局部变量会占用较多的内存空间 3.递归函数的效率较低，尤其是在递归层数较深时